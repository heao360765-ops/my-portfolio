 await mp.screenshot({path:out+'/05b-loading-mobile.png'});
 check('Mobile loading display fits viewport',await mp.locator('.intro-loader').evaluate(e=>e.getBoundingClientRect().right<=innerWidth));
 await mp.waitForFunction(()=>document.querySelector('.portfolio-intro')?.dataset.stage==='welcome');
 await mp.waitForTimeout(1000);
 check('Mobile intro has no horizontal overflow',await mp.locator('.portfolio-intro').evaluate(d=>d.scrollWidth<=d.clientWidth+1));
 await mp.screenshot({path:out+'/06-welcome-mobile.png'});
