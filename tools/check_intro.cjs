const {chromium}=require('playwright');
const fs=require('node:fs');
const base=process.env.SITE_URL||'http://127.0.0.1:4190/';
const out=process.env.SITE_ARTIFACTS||'D:/AI-Work/artifacts/portfolio-intro-20261022/qa';
fs.mkdirSync(out,{recursive:true});
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const context=await browser.newContext({viewport:{width:1440,height:960}});
 const page=await context.newPage(); const errors=[],results=[];
 const check=(name,passed)=>{results.push({name,passed:!!passed});if(!passed)throw Error(name)};
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base,{waitUntil:'networkidle'});
 const dialog=page.locator('.portfolio-intro');
 check('First visit opens prologue',await dialog.evaluate(d=>d.open));
 check('Body is locked',await page.locator('body').evaluate(b=>b.classList.contains('intro-open')));
 await page.screenshot({path:out+'/01-boot.png'});
 await page.waitForTimeout(3600);
 await page.locator('[data-pause]').click();
 const text=await dialog.locator('.intro-dialogue').innerText();
 await page.waitForTimeout(700);
 check('Pause freezes dialogue',text===await dialog.locator('.intro-dialogue').innerText());
 await page.screenshot({path:out+'/02-dialogue.png'});
 await page.locator('[data-pause]').click();
 await page.locator('.portfolio-intro.is-ready').waitFor({timeout:16000});
 check('All four dialogue lines complete',await dialog.locator('.intro-line:not([hidden])').count()===4);
 check('Three meaningful entry choices',await dialog.locator('.intro-choices button,.intro-choices a').count()===3);
 await page.screenshot({path:out+'/03-ready-desktop.png'});
 await page.locator('[data-enter]').click();await dialog.waitFor({state:'detached'});
 check('Entering unlocks page',!(await page.locator('body').evaluate(b=>b.classList.contains('intro-open'))));
 check('Focus returns to portfolio heading',await page.locator('#intro-title').evaluate(e=>document.activeElement===e));
 await page.reload({waitUntil:'networkidle'});
 check('Same-session reload does not repeat',await dialog.count()===0);
 await page.locator('[data-replay-intro]').click();
 check('Replay opens again',await dialog.evaluate(d=>d.open));
 await page.keyboard.press('Escape');await dialog.waitFor({state:'detached'});
 check('Escape returns focus to replay',await page.locator('[data-replay-intro]').evaluate(e=>document.activeElement===e));
 const mobile=await browser.newContext({viewport:{width:375,height:812}});const mp=await mobile.newPage();
 await mp.goto(base,{waitUntil:'networkidle'});
 await mp.locator('.portfolio-intro.is-ready').waitFor({timeout:18000});
 check('Mobile intro has no horizontal overflow',await mp.locator('.portfolio-intro').evaluate(d=>d.scrollWidth<=d.clientWidth+1));
 await mp.screenshot({path:out+'/04-ready-mobile.png'});
 await mp.locator('[data-hardware]').click();await mp.locator('.portfolio-intro').waitFor({state:'detached'});
 check('Hardware choice focuses section',await mp.locator('#hardware').evaluate(e=>document.activeElement===e));
 await mp.locator('[data-replay-intro]').click();await mp.locator('[data-skip]').click();
 await mp.locator('.portfolio-intro').waitFor({state:'detached'});
 check('Skip works on touch layout',await mp.locator('.portfolio-intro').count()===0);
 const reduced=await browser.newContext({reducedMotion:'reduce'});const rp=await reduced.newPage();
 await rp.goto(base,{waitUntil:'networkidle'});
 check('Reduced motion skips automatic prologue',await rp.locator('.portfolio-intro').count()===0);
 await rp.locator('[data-replay-intro]').click();
 check('Reduced motion replay shows completed static dialogue',await rp.locator('.portfolio-intro.is-ready').count()===1);
 await rp.locator('[data-game]').click();await rp.waitForURL(base+'games/wuxitown/');
 check('Game choice opens competition site',await rp.locator('.portfolio-intro').count()===0);
 const direct=await browser.newContext();const dp=await direct.newPage();
 await dp.goto(base+'#hardware',{waitUntil:'networkidle'});
 check('Direct section links skip prologue',await dp.locator('.portfolio-intro').count()===0);
 await dp.goto(base+'games/wuxitown/',{waitUntil:'networkidle'});
 check('Competition link never loads portfolio prologue',await dp.locator('script[src$="intro.js"]').count()===0&&await dp.locator('.portfolio-intro').count()===0);
 check('No script errors',errors.length===0);
 fs.writeFileSync(out+'/report.json',JSON.stringify({base,results,errors},null,2));
 console.log(JSON.stringify({checks:results.length,passed:results.filter(r=>r.passed).length,errors},null,2));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
