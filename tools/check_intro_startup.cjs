const {chromium}=require('playwright');
const fs=require('node:fs');
const base=process.env.SITE_URL||'http://127.0.0.1:4190/';
const out=process.env.SITE_ARTIFACTS||'D:/AI-Work/artifacts/portfolio-cinematic-20261022/startup-qa';
fs.mkdirSync(out,{recursive:true});
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const results=[];const check=(name,passed)=>{results.push({name,passed:!!passed});if(!passed)throw Error(name)};
 try{
  const c=await browser.newContext({viewport:{width:1280,height:720}});const p=await c.newPage();
  let release;const gate=new Promise(r=>release=r);
  await p.route('**/intro.js*',async route=>{await gate;await route.continue()});
  await p.goto(base,{waitUntil:'commit'});
  await p.locator('#intro-title').waitFor({state:'attached'});
  check('First-paint guard is present before animation script',await p.locator('html').evaluate(e=>e.classList.contains('intro-pending')));
  check('Portfolio remains invisible during slow script load',!(await p.locator('#intro-title').isVisible()));
  await p.screenshot({path:out+'/01-first-paint.png'});
  release();await p.locator('.portfolio-intro').waitFor();
  check('Guard hands over directly to modal',await p.locator('.portfolio-intro').evaluate(d=>d.open)&&!(await p.locator('html').evaluate(e=>e.classList.contains('intro-pending'))));
  await p.waitForFunction(()=>document.querySelector('.portfolio-intro')?.dataset.stage==='archive');
  check('Loading scene has a light background',await p.locator('.portfolio-intro').evaluate(d=>getComputedStyle(d).backgroundColor==='rgb(232, 233, 228)'));
  await p.waitForFunction(()=>document.querySelector('.portfolio-intro')?.dataset.stage==='welcome');
  await p.waitForTimeout(500);
  check('Welcome uses upright condensed type',await p.locator('.intro-welcome h2').evaluate(e=>getComputedStyle(e).fontStyle==='normal'&&getComputedStyle(e).fontFamily.includes('ArchiveDIN')));
  check('Industrial font has loaded',await p.evaluate(()=>document.fonts.check('500 40px ArchiveDIN')));
  await p.locator('[data-skip]').click();await p.locator('.portfolio-intro').waitFor({state:'detached'});
  const failed=await browser.newContext();const fp=await failed.newPage();
  await fp.route('**/intro.js*',r=>r.abort());await fp.goto(base,{waitUntil:'domcontentloaded'});
  await fp.locator('#intro-title').waitFor({state:'visible',timeout:6500});
  check('Unavailable animation never permanently hides portfolio',await fp.locator('#intro-title').isVisible());
  const late=await browser.newContext();const lp=await late.newPage();
  await lp.route('**/intro.js*',async r=>{await new Promise(resolve=>setTimeout(resolve,5200));await r.continue()});
  await lp.goto(base,{waitUntil:'domcontentloaded'});await lp.waitForTimeout(500);
  check('Very late script does not cover an already visible portfolio',await lp.locator('.portfolio-intro').count()===0&&await lp.locator('#intro-title').isVisible());
  const nojs=await browser.newContext({javaScriptEnabled:false});const np=await nojs.newPage();await np.goto(base);
  check('Without JavaScript portfolio remains readable',await np.locator('#intro-title').isVisible());
  const audioContext=await browser.newContext();const ap=await audioContext.newPage();
  let releaseAudio;const audioGate=new Promise(resolve=>releaseAudio=resolve);
  await ap.route('**/entry-voice-zh-v7.mp3',async r=>{await audioGate;await r.continue()});
  await ap.addInitScript(()=>{
   const NativeAudio=window.Audio;window.Audio=function(...args){const a=new NativeAudio(...args);window.__testAudio=a;return a};
   const play=HTMLMediaElement.prototype.play;let blocked=false;
   HTMLMediaElement.prototype.play=function(){if(!blocked){blocked=true;return Promise.reject(new DOMException('Test autoplay restriction','NotAllowedError'))}return play.call(this)};
  });
  await ap.goto(base,{waitUntil:'domcontentloaded'});
  await ap.waitForFunction(()=>document.querySelector('.portfolio-intro')?.dataset.voice==='blocked');
  check('Autoplay rejection exposes enable control',await ap.locator('button[data-sound]').innerText()==='开启播报');
  await ap.locator('button[data-sound]').click();
  check('Audio buffering is shown honestly',await ap.locator('button[data-sound]').innerText()==='播报加载中');
  releaseAudio();
  await ap.waitForFunction(()=>document.querySelector('.portfolio-intro')?.dataset.voice==='on'&&window.__testAudio.readyState>=2&&!window.__testAudio.paused&&window.__testAudio.currentTime>.1);
  check('User can enable real packaged speech',await ap.evaluate(()=>window.__testAudio.readyState>=2&&!window.__testAudio.paused));
  const playingTime=await ap.evaluate(()=>window.__testAudio.currentTime);
  await ap.waitForTimeout(800);
  check('Speech advances continuously instead of seeking to the start',await ap.evaluate(t=>window.__testAudio.currentTime>t+.5,playingTime));
  await ap.locator('[data-pause]').click();const time=await ap.evaluate(()=>window.__testAudio.currentTime);
  await ap.waitForTimeout(400);check('Pause also freezes speech',await ap.evaluate(t=>window.__testAudio.paused&&Math.abs(window.__testAudio.currentTime-t)<.05,time));
  await ap.locator('[data-pause]').click();await ap.waitForTimeout(250);
  check('Resume continues speech',await ap.evaluate(()=>!window.__testAudio.paused));
  await ap.locator('button[data-sound]').click();check('Voice can be muted',await ap.evaluate(()=>window.__testAudio.paused));
  await ap.locator('button[data-sound]').click();await ap.waitForTimeout(200);
  await ap.locator('[data-skip]').click();await ap.locator('.portfolio-intro').waitFor({state:'detached'});
  check('Skip stops and releases speech',await ap.evaluate(()=>window.__testAudio.paused&&!window.__testAudio.getAttribute('src')));
  fs.writeFileSync(out+'/report.json',JSON.stringify({base,results},null,2));
  console.log(JSON.stringify({checks:results.length,passed:results.filter(r=>r.passed).length},null,2));
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
